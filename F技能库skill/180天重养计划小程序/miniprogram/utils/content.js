// 某天属于哪个阶段
function getPhase(dayNo) {
  if (!dayNo || dayNo < 1) return PHASES[0]
  if (dayNo > 180) return PHASES[5]
  return PHASES[Math.floor((dayNo - 1) / 30)]
}

// 某天的重养小提示
function getTip(dayNo) {
  return TIPS[dayNo] || ''
}

